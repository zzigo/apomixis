// Builds packages/hylon-algos/midi-corpus.js from apps/hylon/public/midi/*.mid so that score
// algorithms (`morph`) can read MIDI material synchronously and deterministically.
// Each file: the first LIMIT seconds, notes as [time ms, duration ms, midi, velocity, channel].
// Run: node tools/build-midi-corpus.mjs
import {readFileSync,writeFileSync,readdirSync} from 'node:fs';
import tonejs from '@tonejs/midi';
const {Midi}=tonejs;
const DIR=new URL('../apps/hylon/public/midi/',import.meta.url),OUT=new URL('../packages/hylon-algos/midi-corpus.js',import.meta.url),LIMIT=150;
const corpus={};
for(const file of readdirSync(DIR).filter(f=>f.endsWith('.mid')).sort()){
  const midi=new Midi(readFileSync(new URL(file,DIR))),notes=[];
  for(const track of midi.tracks)for(const n of track.notes){if(!(n.time>=0&&n.duration>0)||n.time>=LIMIT)continue;notes.push([Math.round(n.time*1000),Math.max(10,Math.round(Math.min(n.duration,LIMIT-n.time)*1000)),n.midi,Math.max(1,Math.round(n.velocity*127)),track.channel+1]);}
  notes.sort((a,b)=>a[0]-b[0]||a[2]-b[2]);
  corpus[file.replace(/\.mid$/,'')]={duration:Math.round(Math.min(LIMIT,midi.duration)*1000),notes};
}
writeFileSync(OUT,`// Generated by tools/build-midi-corpus.mjs from apps/hylon/public/midi (first ${LIMIT} s of each file).\n// [time ms, duration ms, midi, velocity, channel]. Do not edit by hand.\nexport const MIDI_CORPUS=${JSON.stringify(corpus)};\n`);
console.log(Object.entries(corpus).map(([k,v])=>`${k}: ${v.notes.length} notes, ${(v.duration/1000).toFixed(0)} s`).join('\n'));
